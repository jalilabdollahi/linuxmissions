#!/bin/bash
# Which Upload Limit? An 80-vhost nginx config of roughly 6000 lines. The
# directive client_max_body_size appears dozens of times. The uploads vhost is
# in a random position, lists a second server_name, has a commented-out old
# value, a nested "location /api" with a different value, and its server-level
# value is the answer. Other vhosts proxy to uploads.example.com so a plain
# grep for the name finds more than the server_name line.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
mkdir -p .lm-state

R=$RANDOM
awk -v seed="$R" '
function pick(arr, n) { return arr[int(rand() * n) + 1] }
BEGIN {
  srand(seed)
  up = 20 + int(rand() * 40)
  n = split("1m 2m 5m 8m 16m 20m 32m 50m", sizes, " ")
  split("api shop blog docs admin billing mail cdn search status", words, " ")
  print "# nginx-full.conf - generated by vhostgen 3.2 from vhosts.yaml, do not edit by hand"
  print "user www-data;"
  print "worker_processes auto;"
  print "events { worker_connections 4096; }"
  print "http {"
  print "    include /etc/nginx/mime.types;"
  print "    sendfile on;"
  print "    # global default for every vhost that sets nothing"
  print "    client_max_body_size 1m;"
  for (i = 1; i <= 80; i++) {
    name = words[(i % 10) + 1] "-" int((i - 1) / 10 + 1) ".example.com"
    isup = (i == up)
    if (isup) { name = "uploads.example.com" }
    print ""
    print "    # ---- vhost " i " ----"
    print "    server {"
    print "        listen 443 ssl http2;"
    if (isup) { print "        server_name uploads.example.com www-uploads.example.com;" }
    else { print "        server_name " name ";" }
    print "        ssl_certificate /etc/ssl/vhosts/" i ".pem;"
    print "        ssl_certificate_key /etc/ssl/vhosts/" i ".key;"
    print "        access_log /var/log/nginx/vhost" i ".access.log main;"
    print "        error_log /var/log/nginx/vhost" i ".error.log warn;"
    if (isup) {
      upval = sizes[1 + int(rand() * n)]
      do { apival = sizes[1 + int(rand() * n)] } while (apival == upval)
      do { oldval = sizes[1 + int(rand() * n)] } while (oldval == upval || oldval == apival)
      print "        # was " oldval " until the 2023 incident"
      print "        # client_max_body_size " oldval ";"
      print "        client_max_body_size " upval ";"
    } else if (i % 2 == 0) {
      print "        client_max_body_size " pick(sizes, n) ";"
    }
    print "        gzip on;"
    print "        gzip_types text/plain text/css application/json;"
    print "        add_header X-Frame-Options SAMEORIGIN;"
    print "        add_header X-Content-Type-Options nosniff;"
    print "        location / {"
    print "            proxy_pass http://backend-" i ".internal:8080;"
    print "            proxy_set_header Host $host;"
    print "            proxy_set_header X-Real-IP $remote_addr;"
    print "            proxy_read_timeout 60s;"
    print "        }"
    print "        location /static/ {"
    print "            root /srv/www/vhost" i ";"
    print "            expires 7d;"
    print "            access_log off;"
    print "        }"
    if (isup) {
      print "        location /api {"
      print "            client_max_body_size " apival ";"
      print "            proxy_pass http://uploads-api.internal:9000;"
      print "            proxy_set_header Host $host;"
      print "        }"
      print "        location /healthz {"
      print "            return 200 ok;"
      print "        }"
    } else if (i % 7 == 0) {
      print "        location /export {"
      print "            # fetches the files from uploads.example.com, see INFRA-212"
      print "            proxy_pass https://uploads.example.com/files;"
      print "            client_max_body_size " pick(sizes, n) ";"
      print "        }"
    }
    for (k = 1; k <= 14; k++) {
      print "        location ~ ^/legacy" k "/(.*)$ {"
      print "            rewrite ^/legacy" k "/(.*)$ /v2/$1 permanent;"
      print "        }"
    }
    print "    }"
  }
  print "}"
  print upval > ".lm-state/answer"
  print apival > ".lm-state/nested"
  print oldval > ".lm-state/old"
}' > nginx-full.conf
cksum nginx-full.conf > .lm-state/inputs
