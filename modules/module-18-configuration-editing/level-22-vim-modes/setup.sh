#!/bin/bash
# A generated 400-line squid.conf. Traps: acl lines outside the LEGACY block (must stay), an
# "acl" word inside a comment of the block, http_port 3128 at lines 119/120/180/181 (range edges)
# and cache_peer lines that also contain 3128, one broken line to join. The expected result is
# computed here and saved in .lm-state/expected.conf.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
mkdir -p .lm-state

python3 - <<'PY'
import random

r = random.Random()
L = []
def filler(i):
    k = r.randint(1, 250)
    return r.choice([
        f"# tuning note {k}: see ticket PROXY-{r.randint(100, 999)}",
        f"acl net{k} src 10.{r.randint(0, 250)}.{r.randint(0, 250)}.0/24",
        f"http_access allow net{k}",
        f"refresh_pattern -i \\.{r.choice(['gif', 'png', 'css', 'js', 'iso'])}$ {r.randint(60, 4320)} {r.randint(10, 90)}% {r.randint(4320, 43200)}",
        f"acl port{k} port {r.randint(1024, 9000)}",
        f"dns_nameservers 10.{r.randint(0, 250)}.0.{r.randint(2, 250)}",
        f"cache_log /var/log/squid/cache{k}.log",
        "",
    ])

L = [filler(i) for i in range(400)]
L[0] = "# squid.conf - rescue box proxy, generated and hand-patched since 2019"
L[1] = "visible_hostname proxy-rescue"
for i in (59, 118, 119, 134, 149, 163, 179, 180, 299):          # 0-based: lines 60, 119, 120, ...
    L[i] = "http_port 3128"
L[154] = "# http_port 3128 was the old default, kept for reference"
L[139] = "cache_peer 10.1.2.3 parent 3128 0 no-query"
L[169] = "cache_peer 10.1.2.4 parent 3128 0 no-query"
# the LEGACY block: lines 210..250
L[209] = "# LEGACY"
for i in range(210, 249):
    n = i - 209
    L[i] = r.choice([f"acl legacy{n} src 192.168.{n}.0/24", f"acl legacy{n} src 172.16.{n}.0/24",
                     f"http_access allow legacy{n}", f"# legacy note {n}"])
L[210] = "# acl entries below were generated by squidGuard 1.4"
L[211] = "acl legacy_start src 192.168.0.0/16"
L[247] = "acl legacy_end src 172.16.0.0/12"
L[248] = "http_access deny legacy_end"
L[249] = "# END LEGACY"
L[208] = "acl before_legacy src 10.99.0.0/16"
L[250] = "acl after_legacy src 10.98.0.0/16"
for i in list(range(0, 209)) + list(range(251, 400)):          # outside the block: no accidental http_port / markers
    if L[i].startswith(("http_port", "# LEGACY", "# END")) and L[i] != "http_port 3128":
        L[i] = "# unused"
for i in range(209, 250):
    assert not L[i].startswith("http_port")
L[319] = "# ---- local overrides below ----"
L[359] = "cache_dir ufs /var/spool/squid 2000 16"
L[360] = "    256"
open("squid.conf", "w").write("\n".join(L) + "\n")

mem, obj = r.choice([256, 512, 1024]), r.choice([32, 64, 128])
snippet = ["# local overrides (ticket PROXY-88)", f"cache_mem {mem} MB", f"maximum_object_size {obj} MB"]
open("snippet.conf", "w").write("\n".join(snippet) + "\n")

# Expected result.
E = list(L)
a, b = E.index("# LEGACY"), E.index("# END LEGACY")
E = [l for i, l in enumerate(E) if not (a < i < b and l.startswith("acl "))]
orig = list(L)
out = []
for l in E:
    out.append(l)
exp = []
# http_port in original lines 120..180 only: rebuild from the original numbering
removed_before_180 = 0      # the LEGACY block starts after line 200, so numbering up to 180 is unchanged
for i, l in enumerate(E):
    if 119 <= i <= 179 and l.startswith("http_port 3128"):
        l = l.replace("3128", "3129", 1)
    exp.append(l)
m = exp.index("# ---- local overrides below ----")
exp[m + 1:m + 1] = snippet
j = exp.index("cache_dir ufs /var/spool/squid 2000 16")
exp[j:j + 2] = [exp[j] + " " + exp[j + 1].strip()]
open(".lm-state/expected.conf", "w").write("\n".join(exp) + "\n")
open(".lm-state/orig_acl_outside", "w").write(str(sum(1 for i, l in enumerate(orig) if l.startswith("acl ") and not (a < i < b))))
PY
cp squid.conf .lm-state/original.conf

cat > CHANGES.txt <<'TXT'
squid.conf - changes for the rescue box (line numbers refer to the file as it is now)

 1. Delete every line that starts with "acl" inside the "# LEGACY" ... "# END LEGACY" block.
    acl lines outside the block stay.
 2. Change "http_port 3128" to "http_port 3129", but only on lines 120 to 180 (inclusive).
 3. Insert the contents of snippet.conf right after the line "# ---- local overrides below ----".
 4. The cache_dir line is broken over two lines: join it into one line, single space between.
 5. Save the file.
TXT
