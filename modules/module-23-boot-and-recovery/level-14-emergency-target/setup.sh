#!/bin/bash
# Every Boot Ends in Emergency Mode. sysroot/etc/default/grub plus default/grub.d/*.cfg
# set GRUB_CMDLINE_LINUX. The debug option is there twice (main file: one spelling,
# grub.d/99-debug.cfg appends the other; which is which is random). A level-local
# update-grub mock sources both like grub-mkconfig and stamps grub.cfg.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
mkdir -p bin .lm-state
R() { echo $((RANDOM % $1)); }

# --- random facts -------------------------------------------------------------
ALLK=(6.8.0-31-generic 6.8.0-45-generic 6.8.0-52-generic 6.11.0-19-generic 5.15.0-118-generic)
K1=${ALLK[$(R 5)]}; K2=${ALLK[$(R 5)]}; K3=${ALLK[$(R 5)]}
KERNELS=$(printf '%s\n' "$K1" "$K2" "$K3" | sort -uV)
ROOTUUID=$(cat /proc/sys/kernel/random/uuid 2>/dev/null || printf '%04x%04x-%04x-4%03x-a%03x-%04x%04x%04x' $RANDOM $RANDOM $RANDOM $RANDOM $RANDOM $RANDOM $RANDOM $RANDOM)
POOL=(net.ifnames=0 biosdevname=0 crashkernel=512M audit=1 ipv6.disable=1 nvme_core.default_ps_max_latency_us=0 mitigations=auto)
A1=${POOL[$(R 7)]}; A2=${POOL[$(R 7)]}; [ "$A1" = "$A2" ] && A2=console=ttyS0,115200n8
if [ $(R 2) -eq 0 ]; then MAINTOK="systemd.unit=emergency.target"; DBGTOK="emergency"; else MAINTOK="emergency"; DBGTOK="systemd.unit=emergency.target"; fi
TICKET=INC-$((4000 + RANDOM % 900))
CLOUDARGS="console=tty1 console=ttyS0"

# --- the mock -----------------------------------------------------------------
cat > bin/update-grub <<'MOCKEOF'
#!/bin/bash
# update-grub (mock): regenerates boot/grub/grub.cfg of the captured server in sysroot/ the way
# grub-mkconfig does: it sources etc/default/grub, then every etc/default/grub.d/*.cfg in
# name order (later files win), and writes one menu entry per kernel in boot/. It prints
# its progress on stderr and ends grub.cfg with a '# lm-update-grub' checksum stamp.
# usage: update-grub          (no options; same as grub-mkconfig -o /boot/grub/grub.cfg)
# Exit status: 0 on success, 1 on error.
HERE=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
[ "$(basename "$HERE")" = bin ] && HERE=$(dirname "$HERE")
S=${LM_SYSROOT:-$HERE/sysroot}
[ -f "$S/etc/default/grub" ] || { echo "update-grub: /etc/default/grub: No such file or directory" >&2; exit 1; }
[ -d "$S/boot/grub" ] || { echo "update-grub: /boot/grub: No such file or directory" >&2; exit 1; }
FILES=("$S/etc/default/grub")
for f in "$S"/etc/default/grub.d/*.cfg; do [ -e "$f" ] && FILES+=("$f"); done
for f in "${FILES[@]}"; do echo "Sourcing file \`${f#"$S"}'" >&2; done
mapfile -d '' V < <(bash -c '
  set -a
  for f in "$@"; do . "$f" || exit 1; done
  printf "%s\0" "${GRUB_DEFAULT-0}" "${GRUB_TIMEOUT-5}" "${GRUB_DISTRIBUTOR:-Ubuntu}" "$GRUB_CMDLINE_LINUX" "$GRUB_CMDLINE_LINUX_DEFAULT"
' _ "${FILES[@]}")
[ "${#V[@]}" -eq 5 ] || { echo "update-grub: error in the settings files" >&2; exit 1; }
DEF=${V[0]}; TMO=${V[1]}; DIST=${V[2]}
norm() { set -- $*; echo "$*"; }
CMD=$(norm ${V[3]}); CMDD=$(norm ${V[4]})
ROOTUUID=$(awk '$1 !~ /^#/ && $2 == "/" { sub(/^UUID=/, "", $1); print $1; exit }' "$S/etc/fstab" 2>/dev/null)
[ -n "$ROOTUUID" ] || ROOTUUID=00000000-0000-0000-0000-000000000000
echo "Generating grub configuration file ..." >&2
KS=$(ls "$S"/boot/vmlinuz-* 2>/dev/null | sed 's|.*/vmlinuz-||' | sort -rV)
entry() {  # entry TITLE VERSION recovery? indent
  local title=$1 v=$2 rec=$3 ind=$4 args
  if [ -n "$rec" ]; then args=$(norm "ro recovery nomodeset dis_ucode_ldr $CMD"); else args=$(norm "ro $CMD $CMDD"); fi
  printf "%smenuentry '%s' --class ubuntu --class gnu-linux --class gnu --class os \$menuentry_id_option 'gnulinux-%s-%s-%s' {\n" "$ind" "$title" "$v" "${rec:-advanced}" "$ROOTUUID"
  printf "%s\trecordfail\n%s\tload_video\n%s\tinsmod gzio\n%s\tinsmod part_gpt\n%s\tinsmod ext2\n" "$ind" "$ind" "$ind" "$ind" "$ind"
  printf "%s\tsearch --no-floppy --fs-uuid --set=root %s\n" "$ind" "$ROOTUUID"
  printf "%s\techo\t'Loading Linux %s ...'\n" "$ind" "$v"
  printf "%s\tlinux\t/boot/vmlinuz-%s root=UUID=%s %s\n" "$ind" "$v" "$ROOTUUID" "$args"
  if [ -e "$S/boot/initrd.img-$v" ]; then
    printf "%s\techo\t'Loading initial ramdisk ...'\n%s\tinitrd\t/boot/initrd.img-%s\n" "$ind" "$ind" "$v"
  fi
  printf "%s}\n" "$ind"
}
body() {
  echo "#"; echo "# DO NOT EDIT THIS FILE"; echo "#"
  echo "# It is automatically generated by grub-mkconfig using templates"
  echo "# from /etc/grub.d and settings from /etc/default/grub"; echo "#"; echo
  echo "### BEGIN /etc/grub.d/00_header ###"
  echo "set default=\"$DEF\""
  echo "set timeout=$TMO"
  echo "### END /etc/grub.d/00_header ###"; echo
  echo "### BEGIN /etc/grub.d/10_linux ###"
  first=1
  for v in $KS; do
    echo "Found linux image: /boot/vmlinuz-$v" >&2
    [ -e "$S/boot/initrd.img-$v" ] && echo "Found initrd image: /boot/initrd.img-$v" >&2
    if [ -n "$first" ]; then entry "$DIST" "$v" "" ""; first=; fi
  done
  echo "submenu 'Advanced options for $DIST' \$menuentry_id_option 'gnulinux-advanced-$ROOTUUID' {"
  for v in $KS; do
    entry "$DIST, with Linux $v" "$v" "" "	"
    entry "$DIST, with Linux $v (recovery mode)" "$v" recovery "	"
  done
  echo "}"
  echo "### END /etc/grub.d/10_linux ###"
}
TMP=$(mktemp "$S/boot/grub/.grub.cfg.XXXXXX") || exit 1
body > "$TMP"
INS=$(cat "${FILES[@]}" <(echo "$KS") | cksum | cut -d' ' -f1)
BSUM=$(cksum < "$TMP" | cut -d' ' -f1)
echo "# lm-update-grub: inputs=$INS body=$BSUM" >> "$TMP"
mv "$TMP" "$S/boot/grub/grub.cfg"
echo "Adding boot menu entry for UEFI Firmware Settings ..." >&2
echo "done" >&2
MOCKEOF
chmod +x bin/update-grub
ln -sf bin/update-grub update-grub

# --- the captured server ------------------------------------------------------
build_root() {  # build_root DIR fixed(1|0)
  local S=$1 fixed=$2 k
  mkdir -p "$S/boot/grub" "$S/etc/default/grub.d"
  for k in $KERNELS; do
    printf 'vmlinuz %s\n' "$k" > "$S/boot/vmlinuz-$k"
    printf 'initrd %s\n' "$k" > "$S/boot/initrd.img-$k"
    printf 'CONFIG %s\n' "$k" > "$S/boot/config-$k"
  done
  printf 'UUID=%s / ext4 errors=remount-ro 0 1\n' "$ROOTUUID" > "$S/etc/fstab"
  local tok=""
  [ "$fixed" = 1 ] || tok=" $MAINTOK"
  cat > "$S/etc/default/grub" <<EOT
# If you change this file, run 'update-grub' afterwards to update
# /boot/grub/grub.cfg.
GRUB_DEFAULT=0
GRUB_TIMEOUT_STYLE=hidden
GRUB_TIMEOUT=$((1 + RANDOM % 8))
GRUB_DISTRIBUTOR=Ubuntu
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash"
GRUB_CMDLINE_LINUX="$A1 $A2$tok"
# old: GRUB_CMDLINE_LINUX="systemd.unit=emergency.target"  (never enabled again)
GRUB_TERMINAL=console
EOT
  cat > "$S/etc/default/grub.d/50-cloudimg-settings.cfg" <<EOT
# Cloud images set the serial console here.
GRUB_CMDLINE_LINUX_DEFAULT="$CLOUDARGS"
EOT
  if [ "$fixed" != 1 ]; then
    cat > "$S/etc/default/grub.d/99-debug.cfg" <<EOT
# TEMP ($TICKET): debugging the boot hang, remove when done
GRUB_CMDLINE_LINUX="\$GRUB_CMDLINE_LINUX $DBGTOK"
EOT
  fi
}
build_root sysroot 0
# the timeout line must be the same in the reference copy
TMO=$(sed -n 's/^GRUB_TIMEOUT=//p' sysroot/etc/default/grub)
mkdir -p .lm-state/good
build_root .lm-state/good/sysroot 1
sed -i "s/^GRUB_TIMEOUT=.*/GRUB_TIMEOUT=$TMO/" .lm-state/good/sysroot/etc/default/grub
LM_SYSROOT="$SANDBOX/.lm-state/good/sysroot" bin/update-grub >/dev/null 2>&1 || { echo "setup: mock failed on the reference root" >&2; exit 1; }
cp .lm-state/good/sysroot/boot/grub/grub.cfg .lm-state/good.cfg
./update-grub >/dev/null 2>&1 || { echo "setup: mock failed" >&2; exit 1; }
cksum bin/update-grub sysroot/etc/default/grub.d/50-cloudimg-settings.cfg > .lm-state/sums
