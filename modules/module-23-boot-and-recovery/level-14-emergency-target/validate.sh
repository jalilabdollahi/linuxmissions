#!/bin/bash
# grub.cfg must be exactly what the mock generates from the current settings (so it was
# regenerated, not hand-edited), no linux line may carry the emergency option, and every
# other kernel argument and menu line must equal the reference build.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
command -v python3 >/dev/null || { echo "❌ validator needs python3"; exit 1; }
if ! cksum bin/update-grub sysroot/etc/default/grub.d/50-cloudimg-settings.cfg 2>/dev/null | cmp -s - .lm-state/sums; then
  echo "❌ the update-grub mock or grub.d/50-cloudimg-settings.cfg was changed; type 'reset' to get them back"
  exit 1
fi
CFG=sysroot/boot/grub/grub.cfg
[ -f "$CFG" ] || { echo "❌ sysroot/boot/grub/grub.cfg is missing; run ./update-grub"; exit 1; }
# What would the mock generate right now from the settings files?
T=$(mktemp -d) || exit 1
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/sysroot"
cp -a sysroot/. "$T/sysroot/"
if ! LM_SYSROOT="$T/sysroot" bin/update-grub >/dev/null 2>&1; then
  echo "❌ ./update-grub fails on the current settings files; fix their syntax"
  exit 1
fi
if ! cmp -s "$CFG" "$T/sysroot/boot/grub/grub.cfg"; then
  echo "❌ grub.cfg is not what ./update-grub generates from the current settings: change the settings, then run ./update-grub (do not edit grub.cfg by hand)"
  exit 1
fi
python3 - "$CFG" .lm-state/good.cfg <<'PYEOF'
import sys
got = [l for l in open(sys.argv[1]).read().splitlines() if not l.startswith("# lm-update-grub")]
want = [l for l in open(sys.argv[2]).read().splitlines() if not l.startswith("# lm-update-grub")]
bad = [l for l in got if l.lstrip().startswith("linux") and "emergency" in l]
if bad:
    rec = sum(1 for l in bad if "recovery" in l)
    print("❌ %d linux line(s) in grub.cfg still contain the emergency option (%d of them in recovery entries)" % (len(bad), rec))
    sys.exit(1)
if len(got) != len(want):
    print("❌ grub.cfg has %d lines, expected %d: the set of menu entries changed" % (len(got), len(want)))
    sys.exit(1)
for g, w in zip(got, want):
    if g.lstrip().startswith("linux\t") or g.lstrip().startswith("linux "):
        if sorted(g.split()) != sorted(w.split()):
            lost = [t for t in w.split() if t not in g.split()]
            extra = [t for t in g.split() if t not in w.split()]
            print("❌ a linux line lost or gained kernel arguments besides the debug option (%s)" %
                  ("missing: " + " ".join(lost) if lost else "unexpected: " + " ".join(extra)))
            sys.exit(1)
    elif g != w:
        print("❌ grub.cfg differs from the expected one outside the linux lines: %s" % g.strip()[:60])
        sys.exit(1)
print("✅ grub.cfg was regenerated by update-grub: no entry boots into emergency mode and every other argument is intact")
PYEOF
