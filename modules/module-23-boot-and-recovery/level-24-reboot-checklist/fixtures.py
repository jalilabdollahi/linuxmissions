"""Builds captured root filesystems for the pre-reboot checklist (used by setup.sh and validate.sh)."""
import os, random, uuid
R = random.SystemRandom()
VERS = ["6.8.0-31-generic", "6.8.0-45-generic", "6.8.0-52-generic", "6.11.0-17-generic", "5.15.0-118-generic", "6.5.0-28-generic"]

def _w(root, rel, text, mode=0o644):
    p = os.path.join(root, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(text); os.chmod(p, mode)

def build(root, default="0", kernel_missing=(), initrd_missing=(), fstab="ok", target="ok", avail=150):
    """default: GRUB default ("0" or "1>2"); *_missing: sets of 'v1'/'v2'; fstab: ok|case|bad;
    target: ok|lib|dangling|absent; avail: MB free on /boot in df.txt."""
    v1, v2 = R.sample(VERS, 2)
    ver = {"v1": v1, "v2": v2}
    ru = str(uuid.UUID(int=R.getrandbits(128), version=4)); hu = str(uuid.UUID(int=R.getrandbits(128), version=4))
    eu = "%04X-%04X" % (R.getrandbits(16), R.getrandbits(16))
    def entry(title, v, ind, rec=False):
        extra = " recovery nomodeset" if rec else " quiet splash"
        return ("%smenuentry '%s' --class ubuntu --class os $menuentry_id_option 'gnulinux-%s-%s' {\n%s\tinsmod ext2\n"
                "%s\tsearch --no-floppy --fs-uuid --set=root %s\n%s\tlinux\t/boot/vmlinuz-%s root=UUID=%s ro%s\n"
                "%s\tinitrd\t/boot/initrd.img-%s\n%s}\n") % (ind, title, v, "recovery" if rec else "simple", ind, ind, ru, ind, v, ru, extra, ind, v, ind)
    cfg = "#\n# DO NOT EDIT THIS FILE\n#\nset default=\"%s\"\nset timeout=5\n### BEGIN /etc/grub.d/10_linux ###\n" % default
    cfg += entry("Ubuntu", v1, "")
    cfg += "submenu 'Advanced options for Ubuntu' $menuentry_id_option 'gnulinux-advanced-%s' {\n" % ru
    cfg += entry("Ubuntu, with Linux " + v1, v1, "\t") + entry("Ubuntu, with Linux %s (recovery mode)" % v1, v1, "\t", True)
    cfg += entry("Ubuntu, with Linux " + v2, v2, "\t") + "}\n"
    cfg += "### END /etc/grub.d/10_linux ###\nmenuentry 'UEFI Firmware Settings' $menuentry_id_option 'uefi-firmware' {\n\tfwsetup\n}\n"
    _w(root, "boot/grub/grub.cfg", cfg)
    for k, v in ver.items():
        if k not in kernel_missing: _w(root, "boot/vmlinuz-" + v, "kernel\n")
        if k not in initrd_missing: _w(root, "boot/initrd.img-" + v, "initrd\n")
    _w(root, "blkid.txt", '/dev/vda2: UUID="%s" BLOCK_SIZE="4096" TYPE="ext4" PARTUUID="%s"\n/dev/vda1: UUID="%s" BLOCK_SIZE="512" TYPE="vfat" PARTUUID="%s"\n'
       '/dev/vdb1: LABEL="data" UUID="%s" BLOCK_SIZE="4096" TYPE="ext4" PARTUUID="%s"\n' % (ru, uuid.uuid4(), eu, uuid.uuid4(), hu, uuid.uuid4()))
    rsrc, esrc = "UUID=" + ru, "UUID=" + eu
    if fstab == "case": rsrc, esrc = "UUID=" + ru.upper(), "UUID=" + eu.lower()
    if fstab == "bad": esrc = "UUID=%04X-%04X" % (R.getrandbits(16), R.getrandbits(16))
    _w(root, "etc/fstab", "# /etc/fstab: static file system information.\n#\n# <file system> <mount point> <type> <options> <dump> <pass>\n\n"
       "%s\t/\text4\terrors=remount-ro\t0\t1\n%s\t/boot/efi\tvfat\tumask=0077\t0\t1\nLABEL=data /data ext4 defaults,nofail 0 2\n"
       "proc /proc proc defaults 0 0\n/swap.img\tnone\tswap\tsw\t0\t0\n" % (rsrc, esrc))
    _w(root, "df.txt", "Filesystem     1M-blocks  Used Available Use%% Mounted on\n/dev/vda3          1007M %4dM %6dM %3d%% /boot\n" % (1007 - avail, avail, (1007 - avail) * 100 // 1007))
    os.makedirs(os.path.join(root, "usr/lib/systemd/system"), exist_ok=True)
    for t in ("multi-user.target", "graphical.target"): _w(root, "usr/lib/systemd/system/" + t, "[Unit]\nDescription=%s\n" % t)
    if not os.path.lexists(os.path.join(root, "lib")): os.symlink("usr/lib", os.path.join(root, "lib"))
    os.makedirs(os.path.join(root, "etc/systemd/system"), exist_ok=True)
    link = os.path.join(root, "etc/systemd/system/default.target")
    if target == "ok": os.symlink("/usr/lib/systemd/system/multi-user.target", link)
    elif target == "lib": os.symlink("/lib/systemd/system/graphical.target", link)
    elif target == "dangling":
        os.remove(os.path.join(root, "usr/lib/systemd/system/graphical.target"))
        os.symlink("/usr/lib/systemd/system/graphical.target", link)
