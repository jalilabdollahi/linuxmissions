#!/bin/bash
# Wargame 20: section-scoped sed edit across 40 INI-style configs.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
rm -rf conf .lm
mkdir -p conf .lm/orig .lm/expected
python3 - <<'PY'
import os, random, re
rnd = random.Random(os.urandom(8))
OLD = ["TLSv1 TLSv1.1 TLSv1.2 TLSv1.3", "TLSv1 TLSv1.1 TLSv1.2", "SSLv3 TLSv1 TLSv1.1 TLSv1.2 TLSv1.3", "TLSv1.1 TLSv1.2", "TLSv1.2 TLSv1.3"]
crlf_file = rnd.randint(1, 40)
nokey = set(rnd.sample(range(1, 41), 4))          # [tls] only has the key commented out
other_port = set(rnd.sample(range(1, 41), 5))     # upstream port not 8080
def sp(): return rnd.choice([" = ", " = ", "=", " =", "= "])
for n in range(1, 41):
    L = []
    ind = rnd.choice(["", "", "", "  ", "\t"])
    def kv(k, v, c=""): return f"{ind}{k}{sp()}{v}{c}"
    sections = []
    sections.append(("global", [kv("name", f"svc-{n:02d}"), kv("port", "8080"), kv("ssl_protocols", rnd.choice(OLD)), kv("workers", rnd.randint(1, 8))]))
    tls = []
    if n in nokey:
        tls += ["# ssl_protocols = TLSv1 TLSv1.1 TLSv1.2", kv("cert", f"/etc/ssl/svc-{n:02d}.pem")]
    else:
        if rnd.random() < .4: tls.append("# example: ssl_protocols = TLSv1 TLSv1.1")
        tls.append(kv("ssl_protocols", rnd.choice(OLD)))
        tls.append(kv("cert", f"/etc/ssl/svc-{n:02d}.pem"))
    sections.append(("tls", tls))
    sections.append(("tls_client", [kv("ssl_protocols", "TLSv1 TLSv1.1 TLSv1.2"), kv("verify", "yes")]))
    up = [kv("host", f"10.1.{n}.{rnd.randint(2,200)}")]
    if rnd.random() < .5: up.append("# port = 8080  (old default)")
    up.append(kv("port", str(9090 if n in other_port else 8080), "  # backend" if rnd.random() < .3 else ""))
    sections.append(("upstream", up))
    sections.append(("admin", [kv("port", "8080"), kv("bind", "127.0.0.1")]))
    if rnd.random() < .5: sections.append(("logging", [kv("level", "info"), "# port = 8080"]))
    head, rest = sections[0], sections[1:]
    rnd.shuffle(rest)
    order = [head] + rest
    lines = ["# generated by cfgmgmt, hand edits welcome", ""]
    for name, body in order:
        lines.append(f"[{name}]"); lines += body; lines.append("")
    nl = "\r\n" if n == crlf_file else "\n"
    orig = nl.join(lines) + nl
    # expected
    out = []; sec = None
    for l in orig.split(nl)[:-1]:
        m = re.match(r"^\s*\[([^\]]+)\]\s*$", l)
        if m: sec = m.group(1)
        elif sec == "tls" and re.match(r"^\s*ssl_protocols\s*=", l):
            l = re.sub(r"^(\s*ssl_protocols\s*=\s*).*$", r"\1TLSv1.2 TLSv1.3", l)
        elif sec == "upstream" and re.match(r"^\s*port\s*=", l):
            l = re.sub(r"^(\s*port\s*=\s*)8080\b", r"\g<1>8443", l)
        out.append(l)
    exp = nl.join(out) + nl
    open(f"conf/svc-{n:02d}.conf", "w", newline="").write(orig)
    open(f".lm/orig/svc-{n:02d}.conf", "w", newline="").write(orig)
    open(f".lm/expected/svc-{n:02d}.conf", "w", newline="").write(exp)
PY
exit 0
