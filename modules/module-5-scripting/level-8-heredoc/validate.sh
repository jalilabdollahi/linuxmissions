#!/bin/bash
# Runs generate.sh in two scratch folders: one with the level's vars.env and one
# with different values, and compares app.conf with the exact expected text.
# Also checks that the template is a heredoc, which is what the level teaches.
SANDBOX="$1"
SCRIPT="$SANDBOX/generate.sh"

if [ ! -f "$SCRIPT" ]; then
  echo "❌ generate.sh is missing (type reset to get it back)"
  exit 1
fi
if ! sed 's/<<<//g' "$SCRIPT" | grep -v '^[[:space:]]*#' | grep -q '<<'; then
  echo "❌ generate.sh does not use a heredoc (<<) for the template yet"
  exit 1
fi

WORK="$(mktemp -d "$SANDBOX/.check.XXXXXX")" || exit 1
trap 'rm -rf "$WORK"' EXIT

LIMIT=""
command -v timeout >/dev/null 2>&1 && LIMIT="timeout 5"

# expected NAME PORT ENV -> the exact config text
expected() {
  printf '%s\n' \
    '# app.conf - generated by generate.sh, do not edit by hand' \
    '[app]' \
    "name = $1" \
    "environment = $3" \
    "listen = 0.0.0.0:$2" \
    "url = http://localhost:$2/" \
    '' \
    '[logging]' \
    'format = $remote_addr "$request" $status'
}

# trial LABEL NAME PORT ENV
trial() {
  local dir="$WORK/$1"
  mkdir -p "$dir"
  cp "$SCRIPT" "$dir/generate.sh"
  printf 'APP_NAME=%s\nAPP_PORT=%s\nAPP_ENV=%s\n' "$2" "$3" "$4" > "$dir/vars.env"
  (cd "$dir" && $LIMIT bash ./generate.sh </dev/null >/dev/null 2>&1)
  if [ ! -f "$dir/app.conf" ]; then
    echo "❌ running generate.sh did not create app.conf in the current directory"
    exit 1
  fi
  expected "$2" "$3" "$4" > "$dir/expected"
  tr -d '\r' < "$dir/app.conf" > "$dir/got"
  if ! cmp -s "$dir/expected" "$dir/got"; then
    n=1
    while :; do
      e="$(sed -n "${n}p" "$dir/expected")"
      g="$(sed -n "${n}p" "$dir/got")"
      [ "$e" != "$g" ] && break
      [ "$n" -gt 50 ] && break
      n=$((n + 1))
    done
    if [ "$1" = "level" ]; then
      echo "❌ app.conf differs from app.conf.example at line $n: got '$g', expected '$e'"
    else
      echo "❌ with APP_NAME=$2 APP_PORT=$3 APP_ENV=$4 in vars.env, line $n of app.conf is '$g', expected '$e'"
    fi
    exit 1
  fi
}

trial level linuxmissions 9090 production
trial other billing-api 7001 staging

echo "✅ generate.sh builds app.conf from vars.env with a heredoc"
exit 0
