#!/bin/bash
# Cron Clone: report-gen works in an interactive terminal but dies under cron,
# because it relies on USER (cron sets LOGNAME, not USER) and on TERM (tput),
# and it runs with `set -eu`. cron.env is the environment a test cron job
# captured. The player reproduces cron's run with env -i, keeps the log, and
# fixes the script.
SANDBOX="$1"
cd "$SANDBOX" || exit 1
mkdir -p data reports

cat > report-gen <<'EOF'
#!/bin/bash
# report-gen - daily sales report, run by cron at 06:00 as user "reports":
#   0 6 * * *  /srv/reports/report-gen >> /var/log/report-gen.log 2>&1
set -eu

echo "== report-gen environment =="
env | grep -Ev '^(PWD|SHLVL|_)=' | LC_ALL=C sort
echo "== building report =="

cd "$(dirname "$0")"
author="$USER"
width=$(tput cols)
mkdir -p reports
{
  echo "Daily sales report $(date +%F), generated by $author"
  printf '%*s\n' "$width" '' | tr ' ' '='
  awk -F, 'NR > 1 { sum[$1] += $2 } END { for (r in sum) printf "%-8s %12.2f\n", r, sum[r] }' data/sales.csv | sort
} > reports/daily.txt
echo "report written to reports/daily.txt"
EOF
chmod +x report-gen

cat > cron.env <<'EOF'
# captured on app-03 by a test job: * * * * * env > /tmp/cron.env (2026-11-09 06:00)
HOME=/home/reports
LOGNAME=reports
MAILTO=ops@example.com
PATH=/usr/bin:/bin
SHELL=/bin/sh
EOF

regions=(emea apac amer latam)
{
  echo "region,amount"
  for i in $(seq 1 $(( 60 + RANDOM % 40 ))); do
    printf '%s,%d.%02d\n' "${regions[$(( RANDOM % 4 ))]}" $(( 20 + RANDOM % 900 )) $(( RANDOM % 100 ))
  done
} > data/sales.csv

cat > MAIL.txt <<'EOF'
From: cron daemon <root@app-03>
Subject: Cron <reports@app-03> /srv/reports/report-gen

(no report this morning, again. Running ./report-gen by hand works fine.)
EOF
