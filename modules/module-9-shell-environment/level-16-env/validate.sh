#!/bin/bash
# 1. cron-run.log: report-gen's own env dump must list exactly cron's variables,
#    and the log must show the failure (stderr captured).
# 2. The fixed report-gen, started from / with only cron's variables, exits 0
#    and writes a correct report.
SANDBOX="$1"
cd "$SANDBOX" || exit 1

CRON_VARS='HOME=/home/reports
LOGNAME=reports
MAILTO=ops@example.com
PATH=/usr/bin:/bin
SHELL=/bin/sh'

if [ ! -f cron-run.log ]; then
  echo "❌ cron-run.log does not exist yet"
  exit 1
fi
if ! grep -q '^== report-gen environment ==' cron-run.log; then
  echo "❌ cron-run.log does not contain report-gen's output (its environment dump is missing)"
  exit 1
fi
dump="$(awk '/^== report-gen environment ==/ {on=1; next} /^== building report ==/ {on=0} on' cron-run.log | LC_ALL=C sort)"
extra="$(LC_ALL=C comm -13 <(printf '%s\n' "$CRON_VARS" | LC_ALL=C sort) <(printf '%s\n' "$dump") | cut -d= -f1 | head -4 | paste -sd, -)"
if [ -n "$extra" ]; then
  echo "❌ in cron-run.log report-gen sees variables cron does not have ($extra); start it with an empty environment plus cron.env"
  exit 1
fi
missing="$(LC_ALL=C comm -23 <(printf '%s\n' "$CRON_VARS" | LC_ALL=C sort) <(printf '%s\n' "$dump") | cut -d= -f1 | paste -sd, -)"
if [ -n "$missing" ]; then
  echo "❌ in cron-run.log report-gen is missing cron's variables: $missing"
  exit 1
fi
if ! grep -Eq 'unbound variable|tput' cron-run.log; then
  if grep -q 'report written' cron-run.log; then
    echo "❌ cron-run.log shows a successful run; capture the failing run (before your fix)"
  else
    echo "❌ cron-run.log does not show the error message; it went to stderr, capture that too"
  fi
  exit 1
fi

if [ ! -f report-gen ]; then
  echo "❌ report-gen is missing (type reset)"
  exit 1
fi
out="$(cd / && env -i $(printf '%s\n' "$CRON_VARS") "$SANDBOX/report-gen" 2>&1)"
code=$?
if [ "$code" -ne 0 ]; then
  err="$(printf '%s\n' "$out" | grep -E 'line [0-9]+|tput|not found|No such' | head -1)"
  echo "❌ report-gen still fails under cron's environment (exit $code)${err:+: $err}"
  exit 1
fi
if [ ! -f reports/daily.txt ]; then
  echo "❌ report-gen exited 0 but reports/daily.txt was not written"
  exit 1
fi
head1="$(sed -n 1p reports/daily.txt)"
case "$head1" in
  *"generated by ") echo "❌ the report header names no author (\"generated by \" is empty); under cron, who is the user?"; exit 1 ;;
  "Daily sales report"*"generated by "?*) ;;
  *) echo "❌ the first line of reports/daily.txt is not the report header any more"; exit 1 ;;
esac
if ! sed -n 2p reports/daily.txt | grep -Eq '^={20,}$'; then
  echo "❌ the ruler line under the header is missing or too short; pick a sensible width when there is no terminal"
  exit 1
fi
want="$(awk -F, 'NR > 1 { sum[$1] += $2 } END { for (r in sum) printf "%-8s %12.2f\n", r, sum[r] }' data/sales.csv | sort)"
if [ "$(sed -n '3,$p' reports/daily.txt)" != "$want" ]; then
  echo "❌ the region totals in reports/daily.txt are not right any more"
  exit 1
fi

echo "✅ cron-run.log reproduces cron's failure, and report-gen now works with cron's bare environment"
exit 0
